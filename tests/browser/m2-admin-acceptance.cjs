'use strict';
const assert = require('node:assert/strict');
module.exports = async function ({ page, dir, engine, item, secondItem }) {
    const { api } = require('./m2-support.cjs')(dir);
    const checks = [], media = '/Danmuku/Media/' + item, other = '/Danmuku/Media/' + secondItem;
    const stable = value => Array.isArray(value) ? value.map(stable) : value && typeof value === 'object'
        ? Object.fromEntries(Object.entries(value).filter(([k]) => k !== 'checkedAtUtcMs').map(([k, v]) => [k, stable(v)])) : value;
    let accept = true;
    page.removeAllListeners('dialog');
    page.on('dialog', dialog => accept ? dialog.accept() : dialog.dismiss());
    const editor = page.locator('#dm-plan-editor');
    const select = async id => { await page.locator('#dm-media-list button[data-media-id="' + id + '"]').click(); await page.getByRole('button', { name: '新建合并方案', exact: true }).waitFor(); };
    const ready = () => page.waitForFunction(() => document.querySelector('#dm-plan-editor button.dm-primary')?.disabled === false);
    const newDraft = async name => {
        await page.getByRole('button', { name: '新建合并方案', exact: true }).click();
        await editor.getByRole('textbox', { name: '方案名称', exact: true }).fill(name);
        await editor.getByRole('searchbox', { name: '来源文件搜索', exact: true }).fill('m2-source');
        await editor.getByRole('button', { name: '查找来源文件', exact: true }).click();
        await editor.getByRole('button', { name: '添加片段', exact: true }).first().click();
        await ready();
    };
    await newDraft(engine + '-late-save');
    const previewPattern = new RegExp('/Danmuku/Media/' + item + '/CombinePlans/Preview');
    await page.route(previewPattern, route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"injected statistics failure"}' }));
    await editor.getByRole('textbox', { name: '片段 1 视频起点', exact: true }).fill('00:01');
    await editor.getByRole('status').filter({ hasText: '统计失败' }).waitFor();
    assert(await editor.getByRole('button', { name: '保存方案', exact: true }).isDisabled());
    await page.unroute(previewPattern);
    await editor.getByRole('button', { name: '重新统计', exact: true }).click(); await ready();
    checks.push('statistics failure disables save; explicit retry recovers');
    await editor.getByRole('textbox', { name: '片段 1 源开始', exact: true }).fill('30:00');
    await editor.getByRole('status').filter({ hasText: '全部为空' }).waitFor();
    assert(await editor.getByRole('button', { name: '保存方案', exact: true }).isDisabled());
    await editor.getByRole('textbox', { name: '片段 1 源开始', exact: true }).fill('00:00');
    await editor.getByRole('textbox', { name: '片段 1 视频起点', exact: true }).fill('70:00'); await ready();
    assert.match(await editor.getByRole('status').textContent(), /超出视频时长 [1-9]/);
    await editor.getByRole('textbox', { name: '片段 1 视频起点', exact: true }).fill('00:00'); await ready();
    const tail = editor.getByRole('checkbox', { name: '到文件末尾', exact: true }).first();
    await tail.focus(); await page.keyboard.press('Space');
    assert.equal(await tail.isChecked(), false);
    assert.equal(await editor.getByRole('textbox', { name: '片段 1 源结束', exact: true }).isDisabled(), false);
    await editor.getByRole('textbox', { name: '片段 1 源结束', exact: true }).fill('20:00'); await ready();
    checks.push('zero/all-outside range validation and keyboard checkbox');
    await page.setViewportSize({ width: 1440, height: 900 });
    accept = false;
    await page.locator('[data-tab="files"]').click();
    assert.equal(await page.locator('[data-tab="media"]').getAttribute('aria-current'), 'page');
    assert.equal(await editor.count(), 1);
    await page.locator('#dm-media-list button[data-media-id="' + secondItem + '"]').click();
    assert.equal(await editor.count(), 1);
    accept = true;
    checks.push('declining unsaved navigation preserves editor and media');
    const savePattern = new RegExp('/Danmuku/Media/' + item + '/CombinePlans$');
    await page.route(savePattern, route => route.request().method() === 'POST'
        ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"injected save failure"}' }) : route.continue());
    await editor.getByRole('button', { name: '保存方案', exact: true }).click();
    await editor.getByRole('alert').filter({ hasText: '输入已保留' }).waitFor();
    assert.equal(await editor.getByRole('textbox', { name: '方案名称', exact: true }).inputValue(), engine + '-late-save');
    await page.unroute(savePattern); await ready();
    let entered, release;
    const pending = new Promise(r => { entered = r; }), gate = new Promise(r => { release = r; });
    const beforeOther = await api(other + '/CombinePlans');
    await page.route(savePattern, async route => {
        if (route.request().method() !== 'POST') return route.continue();
        const response = await route.fetch();
        assert.equal(response.status(), 200); entered(); await gate;
        await route.fulfill({ response }).catch(() => {});
    });
    try {
        await editor.getByRole('button', { name: '保存方案', exact: true }).click(); await pending;
        const savedA = await api(media + '/CombinePlans');
        assert(savedA.items.some(p => p.name === engine + '-late-save'));
        await select(secondItem);
        await page.getByRole('button', { name: '新建合并方案', exact: true }).click();
        await editor.getByRole('textbox', { name: '方案名称', exact: true }).fill('B unsaved draft');
        release();
        await page.waitForTimeout(300);
        assert.equal(await editor.getByRole('textbox', { name: '方案名称', exact: true }).inputValue(), 'B unsaved draft');
        assert.deepEqual(stable(await api(other + '/CombinePlans')), stable(beforeOther), 'late A save must never write B');
    } finally { release(); await page.unroute(savePattern); }
    await editor.getByRole('button', { name: '取消编辑', exact: true }).click();
    await select(item);
    checks.push('real A save committed, delayed response does not overwrite real B editor or server state');
    await newDraft(engine + '-late-save');
    await editor.getByRole('button', { name: '保存方案', exact: true }).click();
    await editor.getByRole('alert').filter({ hasText: 'PlanNameConflict' }).waitFor();
    await editor.getByRole('button', { name: /^使用可用名称 / }).click();
    assert.match(await editor.getByRole('textbox', { name: '方案名称', exact: true }).inputValue(), /^combine-\d+$/);
    await ready(); await editor.getByRole('button', { name: '保存方案', exact: true }).click();
    await editor.waitFor({ state: 'detached' });
    checks.push('name conflict preserves input and explicit available-name recovery succeeds');
    return checks;
};
